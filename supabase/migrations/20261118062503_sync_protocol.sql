-- Atomic revisioned sync. All identity comes from auth.uid(), never from payload user_id.
create table if not exists public.user_sync_state (
 user_id uuid primary key references auth.users(id) on delete cascade,
 revision bigint not null default 0 check(revision>=0)
);
create table if not exists public.sync_receipts (
 user_id uuid not null references auth.users(id) on delete cascade,
 operation_id uuid not null,
 response jsonb not null,
 created_at timestamptz not null default now(),
 primary key(user_id,operation_id)
);
create table if not exists public.personal_review_history (
 user_id uuid not null references auth.users(id) on delete cascade,
 operation_id uuid not null,
 payload jsonb not null check(octet_length(payload::text)<=4096),
 reason text not null,
 primary key(user_id,operation_id)
);
create table if not exists public.verified_card_points (
 user_id uuid not null references auth.users(id) on delete cascade,
 card_id text not null,
 points smallint not null default 0 check(points between 0 and 6),
 next_review_day date not null default current_date,
 primary key(user_id,card_id)
);
create table if not exists public.ranked_vocab_ids (id text primary key);
alter table public.user_sync_state enable row level security;
alter table public.sync_receipts enable row level security;
alter table public.personal_review_history enable row level security;
alter table public.verified_card_points enable row level security;
alter table public.ranked_vocab_ids enable row level security;
revoke all on public.user_sync_state,public.sync_receipts,public.personal_review_history,public.verified_card_points,public.ranked_vocab_ids from public,anon,authenticated;
grant select on public.user_sync_state,public.personal_review_history to authenticated;
drop policy if exists sync_state_own on public.user_sync_state;
create policy sync_state_own on public.user_sync_state for select to authenticated using(user_id=(select auth.uid()));
drop policy if exists personal_history_own on public.personal_review_history;
create policy personal_history_own on public.personal_review_history for select to authenticated using(user_id=(select auth.uid()));
insert into public.user_sync_state(user_id) select id from public.profiles on conflict do nothing;
alter table public.review_events add column if not exists verified boolean not null default false;
alter table public.review_events add column if not exists verified_delta smallint not null default 0 check(verified_delta between -1 and 1);
-- Old clients may record unverified history, but cannot assert verified=true.
revoke insert,update on public.review_events from anon,authenticated;
grant insert(user_id,operation_id,card_id,card_type,correct,from_box,to_box,review_day) on public.review_events to authenticated;

create or replace function public.touch_sync_revision()
returns trigger language plpgsql security definer set search_path=public as $$
declare uid uuid;
begin
 if tg_table_name='profiles' then
   uid:=new.id;
   if tg_op='UPDATE' and new.settings is not distinct from old.settings then return null; end if;
 else
   uid:=case when tg_op='DELETE' then old.user_id else new.user_id end;
 end if;
 if not exists(select 1 from auth.users where id=uid) then return null; end if;
 if current_setting('app.sync_user',true)=uid::text then return null; end if;
 insert into public.user_sync_state(user_id,revision) values(uid,1)
 on conflict(user_id) do update set revision=user_sync_state.revision+1;
 return null;
end $$;
revoke all on function public.touch_sync_revision() from public,anon,authenticated;
drop trigger if exists cards_sync_revision on public.cards;
create trigger cards_sync_revision after insert or update or delete on public.cards for each row execute function public.touch_sync_revision();
drop trigger if exists profiles_sync_revision on public.profiles;
create trigger profiles_sync_revision after insert or update of settings on public.profiles for each row execute function public.touch_sync_revision();

create or replace function public.get_sync_revision()
returns bigint language plpgsql security definer set search_path=public as $$
declare rev bigint;
begin
 if auth.uid() is null or not public.is_active_user() then raise exception 'not authorized' using errcode='42501'; end if;
 insert into public.user_sync_state(user_id) values(auth.uid()) on conflict do nothing;
 select revision into rev from public.user_sync_state where user_id=auth.uid();
 return rev;
end $$;
revoke all on function public.get_sync_revision() from public,anon;
grant execute on function public.get_sync_revision() to authenticated;

create or replace function public.apply_sync_batch(p_operation uuid,p_revision bigint,p_upserts jsonb,p_deletes jsonb,p_events jsonb,p_settings jsonb,p_expected_user uuid default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
 uid uuid:=auth.uid(); rev bigint; receipt jsonb; item jsonb; ev jsonb; state jsonb; states jsonb:='{}';
 cid text; cur public.cards%rowtype; before_box integer; after_box integer; day_ date; valid boolean; stamp_ timestamptz:=clock_timestamp();
 ranked public.verified_card_points%rowtype; delta_ integer; rejected jsonb:='[]'; stamps jsonb:='{}'; old_writer text;
begin
 if uid is null or not public.is_active_user() then raise exception 'not authorized' using errcode='42501'; end if;
 if p_expected_user is not null and p_expected_user<>uid then raise exception 'session account changed' using errcode='42501'; end if;
 if p_operation is null or p_revision is null or p_upserts is null or p_deletes is null or p_events is null
   or jsonb_typeof(p_upserts)<>'array' or jsonb_typeof(p_deletes)<>'array' or jsonb_typeof(p_events)<>'array'
   or jsonb_array_length(p_upserts)>500 or jsonb_array_length(p_deletes)>500 or jsonb_array_length(p_events)>20000
   or (p_settings is not null and jsonb_typeof(p_settings)<>'object') then raise exception 'invalid sync batch' using errcode='22023'; end if;
 if p_settings is not null and exists(
   select 1 from jsonb_each(p_settings) e where not (
    (e.key in ('soundEnabled','autoSpeak','hapticFeedback','nounsOnlyMode','newWordsFlipCard','overdueRuleSeen','notifyOvertake') and jsonb_typeof(e.value)='boolean')
    or (e.key='language' and e.value in ('"fa"'::jsonb,'"en"'::jsonb))
    or (e.key='speechRate' and case when jsonb_typeof(e.value)='number' then (e.value::text)::numeric between 0.7 and 1.2 else false end)
   )
 ) then raise exception 'invalid settings patch' using errcode='22023'; end if;
 insert into public.user_sync_state(user_id) values(uid) on conflict do nothing;
 select revision into rev from public.user_sync_state where user_id=uid for update;
 select response into receipt from public.sync_receipts where user_id=uid and operation_id=p_operation;
 if found then return receipt; end if;
 if rev<>p_revision then return jsonb_build_object('conflict',true,'revision',rev); end if;
 old_writer:=current_setting('app.sync_user',true);
 perform set_config('app.sync_user',uid::text,true);
 -- Validate transition history before applying final personal card snapshots.
 for ev in select value from jsonb_array_elements(p_events) loop
   if ev->>'operationId' is null then raise exception 'missing operation identity' using errcode='22023'; end if;
   if exists(select 1 from public.review_events where user_id=uid and operation_id=(ev->>'operationId')::uuid)
     or exists(select 1 from public.personal_review_history where user_id=uid and operation_id=(ev->>'operationId')::uuid) then continue; end if;
   cid:=ev->>'cardId';
   state:=states->cid;
   if state is null then
     select * into cur from public.cards where user_id=uid and id=cid;
     state:=case when found then jsonb_build_object('box',cur.box,'type',cur.type) else jsonb_build_object('box',0,'type',ev->>'cardType') end;
   end if;
   before_box:=(ev->>'fromBox')::integer; after_box:=(ev->>'toBox')::integer; day_:=(ev->>'reviewDay')::date;
   valid:= before_box=(state->>'box')::integer and ev->>'cardType'=state->>'type'
     and before_box between 0 and 5 and after_box=case when (ev->>'correct')::boolean then least(6,before_box+1) else greatest(0,before_box-1) end
     and day_ between (now() at time zone 'utc')::date-1 and (now() at time zone 'utc')::date+1
     and exists(select 1 from public.ranked_vocab_ids where id=cid) and ev->>'cardType'='vocab'
     and (exists(select 1 from jsonb_array_elements(p_upserts) u where u->>'id'=cid) or p_deletes ? cid);
   if valid then
     insert into public.verified_card_points(user_id,card_id,next_review_day) values(uid,cid,day_) on conflict do nothing;
     select * into ranked from public.verified_card_points where user_id=uid and card_id=cid for update;
     valid:=day_>=ranked.next_review_day;
   end if;
   if valid then
     delta_:=greatest(0,least(6,ranked.points+after_box-before_box))-ranked.points;
     insert into public.review_events(user_id,operation_id,card_id,card_type,correct,from_box,to_box,review_day,verified,verified_delta)
     values(uid,(ev->>'operationId')::uuid,cid,'vocab',(ev->>'correct')::boolean,before_box,after_box,day_,true,delta_);
     update public.verified_card_points set points=greatest(0,least(6,points+after_box-before_box)),
       next_review_day=case when after_box>=6 then date '9999-12-31' else day_+power(2,after_box)::integer end
     where user_id=uid and card_id=cid;
   else
     insert into public.personal_review_history(user_id,operation_id,payload,reason)
     values(uid,(ev->>'operationId')::uuid,ev,'unverified or expired offline review') on conflict do nothing;
     rejected:=rejected||jsonb_build_array(ev->>'operationId');
   end if;
   states:=jsonb_set(states,array[cid],jsonb_build_object('box',after_box,'type',ev->>'cardType'),true);
 end loop;
 for cid in select jsonb_array_elements_text(p_deletes) loop delete from public.cards where user_id=uid and id=cid; end loop;
 for item in select value from jsonb_array_elements(p_upserts) loop
   cid:=item->>'id';
   if left(cid,7)='shared_' then continue; end if;
   if states ? cid and (states->cid->>'box')::integer<>(item->>'box')::integer then raise exception 'card and event state differ' using errcode='22023'; end if;
   insert into public.cards(user_id,id,type,box,next_review_date,last_reviewed_at,review_count,correct_count,wrong_count,data,created_at,updated_at)
   values(uid,cid,item->>'type',(item->>'box')::smallint,(item->>'next_review_date')::date,(item->>'last_reviewed_at')::timestamptz,
     (item->>'review_count')::integer,(item->>'correct_count')::integer,(item->>'wrong_count')::integer,coalesce(item->'data','{}'),coalesce((item->>'created_at')::timestamptz,now()),stamp_)
   on conflict(user_id,id) do update set type=excluded.type,box=excluded.box,next_review_date=excluded.next_review_date,
    last_reviewed_at=excluded.last_reviewed_at,review_count=excluded.review_count,correct_count=excluded.correct_count,
    wrong_count=excluded.wrong_count,data=excluded.data,updated_at=excluded.updated_at;
   stamps:=jsonb_set(stamps,array[cid],to_jsonb(stamp_),true);
 end loop;
 if p_settings is not null then update public.profiles set settings=(case when jsonb_typeof(settings)='object' then settings else '{}'::jsonb end)||p_settings,updated_at=stamp_ where id=uid; end if;
 update public.user_sync_state set revision=revision+1 where user_id=uid returning revision into rev;
 receipt:=jsonb_build_object('conflict',false,'revision',rev,'stamps',stamps,'personal',rejected);
 insert into public.sync_receipts(user_id,operation_id,response) values(uid,p_operation,receipt);
 perform set_config('app.sync_user',coalesce(old_writer,''),true);
 return receipt;
end $$;
revoke all on function public.apply_sync_batch(uuid,bigint,jsonb,jsonb,jsonb,jsonb,uuid) from public,anon;
grant execute on function public.apply_sync_batch(uuid,bigint,jsonb,jsonb,jsonb,jsonb,uuid) to authenticated;

