#!/usr/bin/env python3
"""Copy the story audio that the published indexes reference into public/story-media/, where Vercel serves it.

  python3 scripts/dictation/stage_media.py           copy what is missing, remove what no index references
  python3 scripts/dictation/stage_media.py --check   report only; exit 1 if anything is missing or extra

Hosting decision (2026-11-16): audio and illustrations are served by Vercel from the app's own origin
(/story-media/...), not from a Supabase bucket. Same origin, so no CORS, no service-role key and no bucket setup in
production; keys are content hashes, so vercel.json caches them for a year.

Source: build/dictation/audio/<mode>/<key>.mp3 (generated by gen_audio.py, not committed).
Target: public/story-media/audio/<mode>/<key>.mp3 plus the Settings sample test.mp3 (committed).
Images are written there directly by prepare_images.py; this script only checks that every referenced image exists.
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
STORIES = REPO / "public" / "data" / "stories"
SRC = REPO / "build" / "dictation" / "audio"
DST = REPO / "public" / "story-media"
EXTRA_AUDIO = ["test.mp3"]   # the Settings "Test" button (gen_audio.py --test-sample)


def referenced() -> tuple[dict[str, set[str]], set[str]]:
    """{mode: {file names}} of audio, and the set of image files (relative to DST) the stories reference."""
    audio: dict[str, set[str]] = {}
    for idx in sorted(STORIES.glob("story-*.audio.*.json")):
        data = json.loads(idx.read_text(encoding="utf-8"))
        names = audio.setdefault(data["mode"], set())
        names.update(f"{e['key']}.mp3" for e in data["sentences"].values())
    for mode in audio:
        audio[mode].update(EXTRA_AUDIO)
    images: set[str] = set()
    for f in sorted(STORIES.glob("story-[0-9][0-9].json")):
        for q in json.loads(f.read_text(encoding="utf-8"))["sequences"]:
            if q.get("image"):
                images.add(f"{q['image']['key']}.webp")
                images.add(f"{q['image']['key']}@800.webp")
    return audio, images


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    audio, images = referenced()
    problems: list[str] = []
    copied = removed = 0
    for mode, names in audio.items():
        dst = DST / "audio" / mode
        have = {p.name for p in dst.glob("*.mp3")} if dst.exists() else set()
        missing = sorted(names - have)
        extra = sorted(have - names)
        if args.check:
            problems += [f"missing audio/{mode}/{n}" for n in missing] + [f"unreferenced audio/{mode}/{n}" for n in extra]
            continue
        dst.mkdir(parents=True, exist_ok=True)
        for n in missing:
            src = SRC / mode / n
            if not src.exists():
                problems.append(f"audio/{mode}/{n}: not generated (run gen_audio.py)")
                continue
            shutil.copy2(src, dst / n)
            copied += 1
        for n in extra:
            (dst / n).unlink()
            removed += 1
        print(f"audio/{mode}: {len(names)} referenced, {copied} copied, {removed} removed")
    have_img = {str(p.relative_to(DST)) for p in (DST / "images").glob("*.webp")} if (DST / "images").exists() else set()
    problems += [f"missing {n} (run prepare_images.py)" for n in sorted(images - have_img)]
    problems += [f"unreferenced {n}" for n in sorted(have_img - images)]
    print(f"images: {len(images)} referenced, {len(have_img)} present")
    total = sum(p.stat().st_size for p in DST.rglob("*") if p.is_file()) if DST.exists() else 0
    print(f"public/story-media: {total / 1e6:.1f} MB")
    for p in problems:
        print("PROBLEM", p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
