#!/usr/bin/env python3
"""
Copies supabase/functions/send-reminders/reminders.ts into index.ts (between the BEGIN/END markers),
so the Supabase dashboard can deploy the function as one file. Run after editing reminders.ts;
tests/reminders.test.ts fails if the copy is out of date.
Usage: python3 scripts/build-edge-function.py
"""
import re
from pathlib import Path

DIR = Path(__file__).resolve().parent.parent / 'supabase/functions/send-reminders'
BEGIN = '// BEGIN reminders.ts (generated by scripts/build-edge-function.py, do not edit here)'
END = '// END reminders.ts'

source = (DIR / 'reminders.ts').read_text(encoding='utf-8')
# Drop the file's own header comment; keep the code
body = re.sub(r'^/\*\*.*?\*/\s*', '', source, count=1, flags=re.S).strip('\n')
index = (DIR / 'index.ts').read_text(encoding='utf-8')
start, end = index.index(BEGIN) + len(BEGIN), index.index(END)
(DIR / 'index.ts').write_text(index[:start] + '\n\n' + body + '\n\n' + index[end:], encoding='utf-8')
print('index.ts updated from reminders.ts')
