#!/usr/bin/env python3
"""Inline tested pure modules for the owner's single-file Dashboard deployment.
Usage: python3 scripts/build-edge-function.py [--check]
"""
import re
import sys
from pathlib import Path

DIR = Path(__file__).resolve().parent.parent / 'supabase/functions/send-reminders'
path = DIR / 'index.ts'
index = path.read_text(encoding='utf-8')
for module in ('reminders', 'delivery', 'pushEndpoint'):
    begin = f'// BEGIN {module}.ts (generated by scripts/build-edge-function.py, do not edit here)'
    end = f'// END {module}.ts'
    source = (DIR / f'{module}.ts').read_text(encoding='utf-8')
    body = re.sub(r'^/\*\*.*?\*/\s*', '', source, count=1, flags=re.S).strip('\n')
    if begin not in index:
        index += f'\n{begin}\n\n{end}\n'
    start, stop = index.index(begin) + len(begin), index.index(end)
    index = index[:start] + '\n\n' + body + '\n\n' + index[stop:]
if '--check' in sys.argv:
    if index != path.read_text(encoding='utf-8'):
        raise SystemExit('Edge function helpers are stale; run scripts/build-edge-function.py')
    print('Single-file Edge helpers verified')
else:
    path.write_text(index, encoding='utf-8')
    print('Single-file Edge helpers updated')
