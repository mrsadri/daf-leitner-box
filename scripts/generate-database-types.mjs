/** Generate public Database types from the same disposable schema used by SQL tests. */
import { applySchema } from './database-schema.mjs';
import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const db=new PGlite();
const jsType=type=>{
  if(type.endsWith('[]'))return `(${jsType(type.slice(0,-2))})[]`;
  if(/^(smallint|integer|bigint|numeric|real|double precision|int2|int4|int8)$/.test(type))return 'number';
  if(type==='boolean')return 'boolean';
  if(type==='json'||type==='jsonb')return 'Json';
  if(type==='void')return 'undefined';
  if(type==='record'||type==='trigger')return 'unknown';
  return 'string';
};
try{
 await applySchema(db);
 const {rows:columns}=await db.query(`select table_name,column_name,is_nullable,column_default,is_identity,data_type,udt_name
 from information_schema.columns where table_schema='public' order by table_name,ordinal_position`);
 const tables=new Map();for(const c of columns){if(!tables.has(c.table_name))tables.set(c.table_name,[]);tables.get(c.table_name).push(c);}
 let source="// Generated by npm run db:types from repository schema + migrations. Do not edit.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport interface Database { public: { Tables: {\n";
 for(const [name,cols]of tables){source+=`${JSON.stringify(name)}: {\n`;for(const mode of ['Row','Insert','Update']){
  source+=`${mode}: {\n`;for(const c of cols){const optional=mode==='Update'||(mode==='Insert'&&(c.column_default!==null||c.is_identity==='YES'||c.is_nullable==='YES'));
   source+=`${JSON.stringify(c.column_name)}${optional?'?':''}: ${mode==='Insert'&&c.is_identity==='YES'?'never':jsType(c.data_type==='ARRAY'?c.udt_name.slice(1)+'[]':c.data_type)+(c.is_nullable==='YES'?' | null':'')};\n`;}
  source+='};\n';}source+='Relationships: [];\n};\n';}
 source+='}; Views: Record<never, never>; Functions: {\n';
 const {rows:funcs}=await db.query(`select p.proname,p.proretset,p.pronargdefaults,format_type(p.prorettype,null) as return_type,
 coalesce((select jsonb_agg(jsonb_build_object('name',p.proargnames[a.ord],'mode',coalesce(p.proargmodes[a.ord],'i'),'type',format_type(a.typ,null)) order by a.ord)
 from unnest(coalesce(p.proallargtypes,p.proargtypes::oid[])) with ordinality a(typ,ord)),'[]'::jsonb) as args
 from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' order by p.proname`);
 for(const f of funcs){const inputs=f.args.filter(a=>a.mode==='i'||a.mode==='b');const outputs=f.args.filter(a=>['o','t','b'].includes(a.mode));
  const args=inputs.map((a,i)=>`${JSON.stringify(a.name??'arg'+i)}${i>=inputs.length-f.pronargdefaults?'?':''}: ${jsType(a.type)}`).join(';');
  const ret=outputs.length?'{'+outputs.map(a=>`${JSON.stringify(a.name)}: ${jsType(a.type)}`).join(';')+'}':jsType(f.return_type);
  source+=`${JSON.stringify(f.proname)}: { Args: ${inputs.length?'{'+args+'}':'Record<never, never>'}; Returns: ${ret}${f.proretset?'[]':''} };\n`;
 }
 source+='}; Enums: Record<never, never>; CompositeTypes: Record<never, never>; } }\n';
 const target=path.join(root,'src/core/database.types.ts');
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==source)throw new Error('Database types are stale; run npm run db:types');}
 else fs.writeFileSync(target,source);
 console.log('Database types '+(process.argv.includes('--check')?'verified':'generated'));
}finally{await db.close();}
